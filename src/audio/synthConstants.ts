// 操作音エンジンが単独で所有する調整定数。曲非依存で、audio だけが参照・所有する値を置く。
// 値は採用理由を先に述べてから示す。実装後のプレイ検証で調整する見積もり値は ★暫定、
// 標準仕様・物理で固定される値は ☆確定 とする。
// 所有境界: src/config/README.md の「単一の所有モジュールが定まる値はその所有モジュールが定義する」に従い、
// 音色の調整値は audio が定義する（src/config/tuning.ts には置かない。src/engine/constants.ts と同型）。
// 出典: docs/research/03-rendering-ui.md §4、docs/research/07-feasibility-and-parameters.md §1.3・§1.4、
//       docs/research/05-asset-procurement.md §15。

import type { EngineContextState } from "./types";

/**
 * 基本オシレーターの波形。
 * 採用理由を先に述べる。遅延に頑健な音にするため、高域の鋭い過渡成分の少ない波形にする。三角波は高次の奇数倍音を
 * 含み高域成分が多いため、それを避けてサイン波（倍音を含まない純音）を基本にする。音色の厚みは常設倍音
 *（SYNTH_BODY_OVERTONE2_GAIN）で別に与える。
 * 出典: 高域の鋭い過渡は時刻が精密に定位され遅延が目立つ（Temporal envelope and fine structure ほかのWeb調査）。★暫定。
 */
export const SYNTH_WAVEFORM: OscillatorType = "sine";

/**
 * 音量の立ち上がり時間（ミリ秒）。
 * 採用理由を先に述べる。打撃的な一点（1ミリ秒未満）の立ち上がりは知覚される打点（音をリズム上の打点として
 * 感じる時刻）が鋭く定まり、固定の遅延がズレとして分かりやすい。立ち上がりを緩めると打点が時間的に曖昧になり
 * 遅延に寛容になりやすい。一方で長くしすぎると音のエネルギーの山が後退してかえって遅く感じうるため、伸ばし過ぎない
 * 20ミリ秒を初期値にする。確定値ではなく、比較試聴で12・20・28ミリ秒を聴き比べて確定する。★暫定。
 */
export const SYNTH_ATTACK_MS = 20;

/**
 * 音量の減衰時間（ミリ秒）。指数減衰が微小値へ達するまでの時間である。
 * 採用理由を先に述べる。余韻は残響（SYNTH_REVERB_*）で作るため、直接音の減衰は現状の200ミリ秒から大きく伸ばさず
 * 250ミリ秒に控えめに留める。直接音まで長く伸ばすと、残響と合わせた実効的な尾が過剰になり、サビの倍速で最短171
 * ミリ秒（research 07 §1.4）の連打で尾が溜まって濁るため。重なる尾はすべて和音の構成音で協和するため濁りは小さい
 * 見込みだが、最短間隔での濁りの有無は検査・試聴で確認する。★暫定。
 */
export const SYNTH_DECAY_MS = 250;

/**
 * 減衰の末尾の余裕（ミリ秒）。
 * 指数減衰が微小値へ落ちてから停止しないと停止時の雑音が出るため、末尾に余裕を取ってから停止する。★暫定。
 */
export const SYNTH_RELEASE_TAIL_MS = 20;

/**
 * 最古音の消音時間（ミリ秒）。
 * 上限到達時の即時停止は雑音になるため、約8ミリ秒で素早く消してから止める。★暫定。
 */
export const SYNTH_STEAL_FADE_MS = 8;

/**
 * 最古音消音の停止の余裕（ミリ秒）。
 * 音量が0へ達した直後に停止すると丸め誤差で段差が出るため、消音終了の少し後に停止する。★暫定。
 */
export const SYNTH_STEAL_STOP_MARGIN_MS = 2;

/**
 * 音量包絡の微小値。
 * 指数減衰の目標は0にできない（指数は0へ到達しない）ため、可聴域以下とみなせる十分小さい正の値を終点にする。☆確定。
 */
export const SYNTH_ENVELOPE_EPSILON = 0.0001;

/**
 * 直接音の高域通過フィルターの遮断周波数（ヘルツ）。
 * 採用理由を先に述べる。利用者の決定により本物のキック・ベースの重低音を通すため、遮断を下げる。約30ヘルツにするのは、
 * 約60〜90ヘルツのキックの基音を通しつつ、可聴下限以下の直流付近の不要な揺れだけは落とすためである。
 * 楽曲低音との濁りは許容する（利用者が決定済み）。★暫定。
 */
export const SYNTH_HIGHPASS_HZ = 30;

/**
 * 残響音の高域通過フィルターの遮断周波数（ヘルツ）。直接音側より高くする。
 * 採用理由を先に述べる。直接音と同じ約30ヘルツまで残響へ通すと、キック・ベースの低域が残響の畳み込みへ入り、
 * 低域の尾が溜まって濁る。残響へ送る前に約180ヘルツ未満を落とすと、直接音には低域を残しつつ余韻だけ濁らせない。★暫定。
 */
export const SYNTH_REVERB_HIGHPASS_HZ = 180;

/**
 * 低域通過フィルターの遮断周波数（ヘルツ）。
 * 採用理由を先に述べる。高域の鋭い成分は時刻が精密に定位され遅延が目立つため、上端を抑えて音を丸くする。
 * 遅延に頑健な温かい音にするため、現状の4500ヘルツから下げて3800ヘルツに置く（研究が薦める3500〜4000ヘルツの中央付近）。
 * 高域通過300ヘルツ（楽曲の低音と歌声基音域を避ける）は変えない。★暫定。
 */
export const SYNTH_LOWPASS_HZ = 3800;

/**
 * 同時発音数の上限。
 * 受け入れ基準「16同時で非破綻」を満たすため上限を16以上にして16音では最古音の消音が起きないようにする。
 * 研究資料の範囲16〜24の上限24を採る。現実の同時発音数（同時押し2〜3点と減衰の重なりで数音）は上限より
 * はるかに少なく節点数は性能上の懸念にならない。★暫定。
 */
export const SYNTH_POLYPHONY_MAX = 24;

/**
 * マスター音量（0以上）。
 * 採用理由を先に述べる。実機試聴で、水滴音は聞こえるが「目立ち過ぎる（大きい）」ことが分かったため、操作音は演奏を
 * 邪魔しない控えめな存在感にしたいという利用者の判断で、複数回の試聴で一律に下げて確定した。
 * 0.38を採るのは、水滴音の単音の最大振幅を約0.045（約マイナス27デシベル）の控えめな水準にして演奏の邪魔にならない
 * ようにしつつ、水滴音は音程のある明瞭な音のため、この水準でも聞き取れる範囲に留めるためである。
 * クリップしないことの確認を述べる。多数同時（同時発音上限ぶん）の最悪条件でも、合算は前段の動的圧縮と最終ソフトクリップ
 *（天井0.99未満）で抑えられ、この音量では最終出力の最大振幅が約0.53に留まる（クリップ前に十分な余裕を残す）。
 * 1未満ではなく1を超える値を採れるのは、この音量が圧縮とソフトクリップの後段ではなく前段（合流の後の動的圧縮の後・
 * 最終ソフトクリップの前）にあり、最終段の柔らかい飽和制限が出力を天井0.99未満へ構造的に収めるためである。
 * クリップしないことの確認を述べる。音声経路は（直接音と残響を合流した後に）動的圧縮、マスター音量、最終ソフトクリップの順
 *（voiceGraph.ts）で、マスター音量は圧縮の後段にあるため単音を潰さず一律に拡大し、多数同時の合算は前段の動的圧縮が頂点を
 * 抑え、最終段の柔らかい飽和制限が出力を天井0.99未満へ収めるため、どの端末でもクリップしない。これはオフライン描画の
 * スモークでも検査する（同一レーン・雑音主体・全レーンの同時多数がいずれも上限以下）。値は実機試聴で確定する★暫定。
 */
export const SYNTH_MASTER_GAIN = 0.38;

/**
 * 1音の頂点音量（0以上1以下）。
 * 現実的な同時発音数では合算しても歪まない頂点振幅。多数同時時は動的圧縮が頂点を抑える。★暫定。
 */
export const SYNTH_VOICE_PEAK = 0.5;

/**
 * 常設の倍音（第2倍音＝1オクターブ上）の、基本音に対する音量比（0以上1以下）。
 * 採用理由を先に述べる。基本波形をサイン（倍音を含まない純音）にしたため、音色に温かみと存在感を与える倍音を
 * 別に常設で足す。協和を崩さないため整数倍にし、最も協和度の高い第2倍音（周波数比2対1）を選ぶ。高域の鋭さを
 * 増やさないよう、第3倍音以上の高い倍音は常設しない。音量比は基本音より十分小さい0.18にして、音程を運ぶ基本音を
 * 埋もれさせない。周波数の倍率は overtoneFrequency と共有する SYNTH_OVERTONE_RATIO（値2）を用いる。★暫定。
 */
export const SYNTH_BODY_OVERTONE2_GAIN = 0.18;

/**
 * 倍音の、基本周波数に対する周波数の倍率。常設倍音と投下時倍音の両方が用いる。
 * 採用理由を先に述べる。協和を崩さないため倍音は基本周波数の整数倍にする（整数倍は倍音列の一員で協和する）。
 * 整数倍のうち2倍は周波数比2対1（1オクターブ上）で最も協和度が高い。音程を変えずに音色だけを変える。
 * この値の整数性は pitch.ts の overtoneFrequency の単体テストで保証する。★暫定。
 */
export const SYNTH_OVERTONE_RATIO = 2;

/**
 * 投下中に追加で重ねる倍音（第2倍音）の、基本音に対する音量比（0以上1以下）。
 * 採用理由を先に述べる。投下中は常設の第2倍音（SYNTH_BODY_OVERTONE2_GAIN 0.18）に、さらに同じ第2倍音を
 * この音量比で足し、第2倍音の成分を厚くして明るく聞こえさせる（周波数重心が通常時より高くなる）。基本音より小さい
 * 0.35（約マイナス9デシベル）にして基本音を埋もれさせない。通常の操作音を柔らかく保つことを優先し、投下時は
 * 「少し明るい」に留める。実機試聴で調整する見積もり値のため ★暫定。
 */
export const SYNTH_OVERTONE_GAIN_RATIO = 0.35;

/**
 * 動的圧縮の閾値（デシベル）。
 * マスター音量0.3で余裕が大きく、少数同時では圧縮を効かせず撥弦の立ち上がりを保ちたい。
 * 閾値をマイナス6デシベル（線形で約0.5）に置くと、合算が大きくなる多数同時のときだけ圧縮が働く。★暫定。
 */
export const SYNTH_COMPRESSOR_THRESHOLD_DB = -6;

/**
 * 動的圧縮の比率。
 * 強い圧縮は音を平板にするため、頂点の頭打ちとして十分かつ自然な4対1にする。★暫定。
 */
export const SYNTH_COMPRESSOR_RATIO = 4;

/**
 * 動的圧縮の膝（デシベル）。
 * 閾値付近で急に圧縮が始まると不自然なため、6デシベルの緩やかな膝で滑らかに移行する。★暫定。
 */
export const SYNTH_COMPRESSOR_KNEE_DB = 6;

/**
 * 動的圧縮の立ち上がり時間（秒）。
 * 圧縮が働くのは多数同時で合算が大きいときに限られ、その状況では個々の立ち上がりの保存より頂点抑制を
 * 優先するため、素早い3ミリ秒で頂点を捉える。★暫定。
 */
export const SYNTH_COMPRESSOR_ATTACK_SEC = 0.003;

/**
 * 動的圧縮の解放時間（秒）。
 * 解放が速すぎると音量が脈打つため、減衰時間250ミリ秒と同程度の250ミリ秒で滑らかに戻す。★暫定。
 */
export const SYNTH_COMPRESSOR_RELEASE_SEC = 0.25;

/**
 * 残響（余韻）の長さ（秒）。
 * 採用理由を先に述べる。余韻として聞こえる長さを保ちつつ、密な連打で尾が溜まらない短さにするため、短い室内の
 * 響き程度の0.35秒にする。サビの倍速で最短171ミリ秒（research 07 §1.4）の連打で尾が大きく重ならないことを
 * 検査・試聴で確認する。★暫定。
 */
export const SYNTH_REVERB_SECONDS = 0.35;

/**
 * 残響の応答特性を作る疑似乱数の種（整数）。
 * 採用理由を先に述べる。同じ種から同じ応答特性を再現でき、実機の発音と検証用のオフライン描画で同じ余韻になるよう、
 * 固定の整数を種にする。値そのものに意味はなく、再現性のための固定値である。☆確定（固定値）。
 */
export const SYNTH_REVERB_SEED = 1337;

/**
 * 残響の応答特性の標本列全体の二乗平均平方根（大きさの指標）の目標値（0以上）。
 * 採用理由を先に述べる。残響ノードの既定の正規化を切る（voiceGraph.ts で normalize=false）ため、残響の音量を
 * 応答特性の大きさと残響音量（SYNTH_REVERB_WET_GAIN）だけで決められるよう、応答特性の二乗平均平方根をこの値に
 * そろえる。基本音より十分小さい0.05にして、余韻が直接音を覆わないようにする。実機試聴で調整する。★暫定。
 */
export const SYNTH_REVERB_TARGET_RMS = 0.05;

/**
 * 残響経路（湿った音）の音量（0以上1以下）。
 * 採用理由を先に述べる。音程を運ぶのは直接音であり、余韻は遅れの印象を薄める補助のため、直接音より十分小さくする。
 * 0.18にして基音を埋もれさせない。直接音と残響を合わせた尾の重なりと、最終出力がクリップしないことは、
 * オフライン描画のスモークと実機試聴で確認する。実機試聴で調整する。★暫定。
 */
export const SYNTH_REVERB_WET_GAIN = 0.18;

/**
 * 最終段の柔らかい飽和制限（ソフトクリップ）の膝の高さ（0より大きく天井より小さい）。
 * 採用理由を先に述べる。これより小さい絶対値の音はそのまま通して音量・音色を変えず、これより大きい音だけを
 * 滑らかに抑える。通常のタップ1回の最終出力（約0.28）より十分高く、かつ多数同時の頂点（約0.97）より低い0.7に
 * 置くことで、通常の音に影響を与えず、多数同時の頂点だけを抑えてクリップを防ぐ。★暫定。
 */
export const SYNTH_SOFTCLIP_KNEE = 0.7;

/**
 * 最終段の柔らかい飽和制限の天井（出力の絶対値の上限。0より大きく1未満）。
 * 採用理由を先に述べる。デジタルの最大値1.0ちょうどに張り付くと耳障りになり得るため、わずかに下げた0.99
 *（約0.09デシベル下）を上限にする。これにより、どの端末・どの入力でも出力は1.0未満に収まり、クリップしない。★暫定。
 */
export const SYNTH_SOFTCLIP_CEILING = 0.99;

/**
 * ソフトクリップの特性曲線の要素数。
 * 採用理由を先に述べる。曲線が滑らかに見える十分な分解能として2048点にする。2のべき乗である必要はないが、
 * 一般的な分解能の値を採る。★暫定。
 */
export const SYNTH_SOFTCLIP_CURVE_SAMPLES = 2048;

/**
 * 未起動を表す AudioContext 状態の初期値。
 * AudioContext を生成する前は標準の状態（"suspended" など）を持たないため、未生成を表す値を別に置く。☆確定。
 */
export const ENGINE_STATE_UNINITIALIZED: EngineContextState = "uninitialized";
