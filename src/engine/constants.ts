// engine 層が所有する調整定数。曲非依存で、engine だけが参照・所有する値を置く。
// 値は理由を先に述べてから示す。実装後のプレイ検証で調整する見積もり値は ★暫定、
// 他の定数から導出する値は式で示し、定数を変えても整合するようにする。
// 所有境界: src/config/tuning.ts 冒頭と src/engine/README.md のとおり、engine 固有の値は engine が定義する。

/**
 * 固定時間刻み（ミリ秒）。★暫定。
 * 満点とする判定の許容幅は前後40ミリ秒（src/config/tuning.ts の JUDGE_PERFECT_WINDOW_MS）。
 * 状態の進行を判定窓の内側で複数回解像するため、満点窓の4分の1の10ミリ秒とする。
 * 減衰外端90ミリ秒も10で割り切れ（9刻み）、毎秒100刻みで負荷も小さい。
 */
export const FIXED_STEP_MS = 10;

/**
 * フレーム時間差クランプ上限（ミリ秒）。
 * 既存の src/app/index.ts の値と scripts/screens-smoke.mjs のタイムアウト算定（最悪毎秒5フレーム想定）が
 * 100ミリ秒クランプに依存するため維持する。タブ復帰や負荷で時刻差が数秒に跳ねてもUI進行が飛ばないための最終防壁。
 */
export const FRAME_DELTA_CLAMP_MS = 100;

/**
 * 再生中の再同期閾値（ミリ秒）。★暫定。
 * 平滑化が許す遅れの上限。位置報告の更新粒度（おおむね50ミリ秒から100ミリ秒）の揺れで誤って再同期しないよう
 * 更新粒度の約2倍を採り、シーク・タブ復帰のような数百ミリ秒以上の飛びだけを再同期で捕捉する。
 */
export const RESYNC_THRESHOLD_MS = 200;

/**
 * 平滑化係数（0以上1以下）。★暫定。
 * 再生位置の報告はおおむね50ミリ秒から100ミリ秒間隔で段階的に更新される。毎フレーム（約16.7ミリ秒）で
 * 報告値へ急追従させると時計が階段状に揺れるため、一次低域通過で数フレームかけて吸収する。
 * 0.2 は報告値との差が1フレームごとに約2割縮む設定で、時定数は概ねフレーム間隔÷0.2≒約83ミリ秒（報告更新粒度と同程度）。
 */
export const SMOOTHING_FACTOR = 0.2;

/**
 * 停止中の再同期閾値（ミリ秒）。★暫定。
 * 停止中は予測で進めないため予測誤差が無く、報告位置のゆらぎは無視できるほど小さい。
 * よって1刻み（固定時間刻み）を超える報告位置の変化は実際の位置移動（シーク）とみなして再同期する。
 * TextAlive 結線後に停止中の報告ゆらぎが大きい環境では、プレイ検証で20ミリ秒程度へ引き上げる余地がある。
 */
export const PAUSED_RESYNC_THRESHOLD_MS = FIXED_STEP_MS;

/**
 * 1フレームの最大刻み回数（導出値）。
 * 通常フレームでゲーム時間が進む最大量は、実経過のクランプ上限（FRAME_DELTA_CLAMP_MS）に、
 * 平滑化補正の最大量（再同期閾値 × 平滑化係数）を加えた量である。これを固定時間刻みで割って導出する。
 * 通常フレームではこの上限に達しないため、上限到達は異常時の安全弁であり、到達時は余剰を捨てず現在時刻へ合わせる。
 */
export const MAX_SIMULATION_STEPS_PER_FRAME = Math.ceil(
  (FRAME_DELTA_CLAMP_MS + RESYNC_THRESHOLD_MS * SMOOTHING_FACTOR) / FIXED_STEP_MS
);
