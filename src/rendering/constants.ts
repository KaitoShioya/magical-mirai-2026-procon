// 面積が小さいため、ブルームに乗ると一点へ集中して白く飽和し白飛びする。これを避けるため、芯と種の最終輝度を
// 反応輝度が最大でもブルーム下限を下回る暗さに保つ。基準色の輝度はおよそ0.58、反応輝度の最大は2.0であり、
