// 花弁の立体的な反り（正規化座標、Issue #60 の目視調整）。採用理由を先に述べる。花弁を完全な平面にすると斜め上から
// 見たとき平面的に見える。出典の数理を先に述べる。花弁の面内の放射状配置は接線ベクトルと法線ベクトルへの分解で表す
// （Web調査: Parametric Flowers, sambrunacini.com。本実装の dir=(cosθ,sinθ)・perp=(-sinθ,cosθ) がこの法線・接線基底に一致）。
// 面外の反りは、成熟した花弁が微分成長により鞍型（長手方向に凸・幅方向に凹のanticlastic曲率）の曲面になるという結論
// （Web調査: Petal shapes of sympetalous flowers, New J. Phys. 14 085014）に倣い、平面の花弁頂点へ上方向の摂動を加えて表す
// （当該文献は鞍型という定性的結論を与えるため、具体の変位はこの結論に整合する本実装のパラメトリックな摂動で与える）。
// 長手方向のアーチ高さ。中央線（半幅0の根元と先端を結ぶ線）を sin(π×長手位置) で持ち上げ、根元と先端を平面に接したまま
// 中ほどを最も高くして長手方向に凸にする。
export const SUNFLOWER_PETAL_CURL_HEIGHT = 0.16;
