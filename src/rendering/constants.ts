export const SUNFLOWER_PETAL_TIP_RISE = 0.1;
// 幅方向のチャンネル深さ。両縁を中央線より持ち上げて凹の溝にし、長手方向の凸と合わせて鞍型（異曲率）にする。
export const SUNFLOWER_PETAL_CUP_DEPTH = 0.06;

